function normalize(value) {
  return String(value || '')
    .normalize('NFKD')
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[إأآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[ؤ]/g, 'و')
    .replace(/[ئ]/g, 'ي')
    .replace(/[؟?!.,،:;؛"'`()\[\]{}]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function arabicDigitsToLatin(value) {
  return String(value).replace(/[٠-٩]/g, digit => String('٠١٢٣٤٥٦٧٨٩'.indexOf(digit)));
}

function directArithmetic(question) {
  const converted = arabicDigitsToLatin(question);
  const match = converted.match(/(?:كم يساوي|احسب|ناتج)\s*([\d\s()+\-*/.]+)/i);
  if (!match) return null;
  const expression = match[1].trim();
  if (!expression || !/^[\d\s()+\-*/.]+$/.test(expression)) return null;
  try {
    const result = Function(`"use strict"; return (${expression})`)();
    if (!Number.isFinite(result)) return null;
    return `الناتج هو: ${Number.isInteger(result) ? result : Number(result.toFixed(6))}.`;
  } catch { return null; }
}

function findIncludedKey(question, table) {
  return Object.keys(table).sort((a,b) => b.length - a.length).find(key => question.includes(key));
}

